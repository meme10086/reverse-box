    t=time.time()
    nw, _ = E.solve_no_rewind(rows)
    dt=time.time()-t
    print(f"关{i}: 参考解通关={ok} 回溯={used} err={rerr} | 无回溯解={'有(!!)' if nw else '无'} ({dt:.2f}s)")
